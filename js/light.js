function lightAnalysis(r){
  const A = analyzeClassic(r);
  const dGan = r.dGan;
  const dog = DOG[dGan];
  const gk = A.gyeok.type === "록겁"
      ? (A.gyeok.name === "양인격" ? ARCHE.겁재 : ARCHE.비견)
      : (ARCHE[A.gyeok.type] || ARCHE.비견);

  // 능력치: 원국 오행 개수를 0~100으로 (0개=15, 4개 이상=95)
  const stats = OH_LIST.map(k=>{
    const cnt = r.oh[k];
    const v = Math.min(95, 15 + cnt*20);
    return {oh:k, name:STAT[k].n, desc:STAT[k].d, cnt, v};
  });
  const best = stats.slice().sort((a,b)=>b.v-a.v)[0];
  const worst= stats.slice().sort((a,b)=>a.v-b.v)[0];

  // 한 줄 별명
  const strong = A.gise.cnt>=2;
  const nick = `${best.name} ${best.v>=75?"만렙":"높은 편"}` + (worst.name===best.name ? "" : ` · ${worst.name} ${worst.cnt===0?"0 (충전 필요)":"낮은 편"}`);
  const title = `${dog.breed} 기질의 ${gk.name}`;

  const situ = SITU[dGan];

  // 대운 라이트
  const cur = new Date().getFullYear() - r.form.y + 1;
  const daeun = r.daeun.map(d=>({
    age:d.age, gz:d.gz, idx:d.idx, sip:d.sip,
    now: cur>=d.age && cur<d.age+10,
    tag: DAEUN_LIGHT[d.sip] || ""
  }));
  const nowD = daeun.find(d=>d.now);

  return {A, dog, gk, stats, best, worst, title, nick, situ, daeun, nowD, cur, strong};
}

