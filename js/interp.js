function daeunNote(r,d){
  const oh=GAN_OH[GAN.indexOf(d.gz[0])], jiOh=JI_OH[JI.indexOf(d.gz[1])];
  const L=[SIP_DAEUN[d.sip], `${ageContext(d.age)}와 겹칩니다.`];
  const minV=Math.min(...OH_LIST.map(k=>r.oh[k])), maxV=Math.max(...OH_LIST.map(k=>r.oh[k]));
  const weak=OH_LIST.filter(k=>r.oh[k]===minV), strong=OH_LIST.filter(k=>r.oh[k]===maxV);
  const inc=[...new Set([oh,jiOh])];
  const fills=inc.filter(k=>weak.includes(k)), piles=inc.filter(k=>strong.includes(k));
  if(fills.length)
    L.push(`들어오는 기운은 <b>${inc.join("·")}</b>입니다. 이 중 ${fills.slice(0,-1).concat([josa(fills[fills.length-1],"은","는")]).join("·")} 원래 사주에 가장 적은(${minV}개) 기운이라, 평소 잘 안 되던 쪽이 이 10년 동안은 자연스러워지는 구간으로 봅니다. ${OH_DESC[fills[0]].what}`);
  else if(piles.length && minV!==maxV)
    L.push(`들어오는 기운은 <b>${inc.join("·")}</b>입니다. 이 중 ${piles.slice(0,-1).concat([josa(piles[piles.length-1],"은","는")]).join("·")} 원래 가장 많은(${maxV}개) 기운이라 강한 성향이 더 진해집니다 — ${OH_DESC[piles[0]].many}`);
  else
    L.push(`들어오는 기운은 <b>${inc.join("·")}</b>입니다. ${OH_DESC[oh].what}`);
  return L;
}

