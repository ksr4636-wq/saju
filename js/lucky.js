/* 방향별 가중치 — 합충과 십성이 취(取)·사(捨)에 각각 다르게 작용한다 */
function dirWeight(dir, ctx, sip, rel){
  if(!dir) return {v:0, t:null};
  const g = SIP_GROUP[sip];
  let v = 0; const why = [];
  if(dir==="in"){
    if(rel==="합")   { v+=17; why.push("오늘은 합(合)이 성립해 묶고 들이는 쪽에 힘이 실립니다."); }
    if(rel==="삼합") { v+=13; why.push("오늘은 삼합(三合)으로 기운이 한데 모입니다. 들이는 결정에 유리합니다."); }
    if(rel==="충")   { v-=19; why.push("오늘은 충(沖)이라 흩어지는 기운입니다. 새로 들이기엔 어긋납니다."); }
    if(g==="재성")   { v += ctx.strong ? 13 : -13;
      why.push(ctx.strong ? "재성이 들어오는데 일간이 이를 감당할 힘이 있어 취(取)하기에 맞습니다."
                          : "재성이 들어오지만 일간이 약해 감당이 버겁습니다. 더 들이면 부담만 커집니다."); }
    if(g==="비겁")   { v-=12; why.push("비겁이 재물을 나누는 날이라 새로 들이는 결정은 불리합니다."); }
    if(g==="인성")   { v+=8;  why.push("인성이 들어와 받아 담는 기운이 됩니다."); }
    if(g==="식상")   { v-=6; }
  } else {
    if(rel==="충")   { v+=19; why.push("오늘은 충(沖)이라 흩고 내보내는 작용이 강합니다. 정리에는 오히려 알맞습니다."); }
    if(rel==="합")   { v-=14; why.push("오늘은 합(合)이 성립해 붙잡는 기운입니다. 끊어내기엔 미련이 남기 쉽습니다."); }
    if(rel==="삼합") { v-=10; why.push("삼합으로 묶이는 날이라 지금 놓으면 아쉬움이 남기 쉽습니다."); }
    if(g==="식상")   { v+=14; why.push("식상은 만들어 내보내는 기운이라 방출과 정리에 어울립니다."); }
    if(g==="재성")   { v += ctx.strong ? -7 : 13;
      if(!ctx.strong) why.push("일간이 약한데 재성이 강해 부담이 큰 날입니다. 덜어내는 편이 낫습니다."); }
    if(g==="인성")   { v-=8;  why.push("인성은 끌어안는 기운이라 오늘은 놓는 결정과 방향이 다릅니다."); }
    if(g==="비겁")   { v+=6; }
  }
  // 방향 요소는 결론을 실제로 가르는 핵심이므로 기본 요소보다 비중을 크게 둔다.
  // (배율 2.0 기준: 같은 날 '살까'와 '팔까'의 결론이 약 51% 확률로 갈린다)
  return {v: Math.round(v*2), t: why[0]||null};
}

